import { policyHash } from '../src/phrase-policy.ts';
import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { once } from 'node:events';
import { openDatabase } from '../src/database.ts';
import { createApp } from '../src/server.ts';
import { fakeDirect } from './fixtures/direct-api.ts';
import { qualityCases, referenceMeanings } from './fixtures/phrase-quality.ts';

test('E1 HTTP: четыре шага, исправление факта, согласия/ledger, повтор, список и полный fixture Direct', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'e1-http-')), db = openDatabase(dir), fake = fakeDirect(), sample = qualityCases[0];
  let profiles = 0, judgments = 0, requests = 0;
  const ai = { profile: async () => { profiles++; return structuredClone(sample.profile); },
    judge: async (_draft, profile, candidates) => { judgments++; assert.equal(profile.offers[0].name, 'Суши с доставкой'); return referenceMeanings(sample, candidates); } };
  ai.groundedJudge = async (draft,profile,candidates) => ({schemaVersion:'judge-v3-grounded-1',judgments:(await ai.judge(draft,profile,candidates)).map(row=>({id:row.id,offerId:row.offerId,decision:row.decision,intent:row.intent,adRelevant:row.adRelevant,reason:row.reason,support:{basis:row.offerId?'equivalent':'unsupported',factRefs:row.offerId?[`${row.offerId}:offer`]:[]},qualifiers:row.brandTerm?[{text:row.brandTerm,kind:row.brand==='product'?'manufacturer':'brand',role:row.brand,basis:row.brand==='own'?'fact':'unsupported',factRefs:row.brand==='own'?['own:0']:[]}]:[]}))});
  const wordstat = async () => { requests++; return sample.queries.map((q,i) => ({ phrase: q.phrase, count: String(100-i) })); };
  const server = createApp(db, undefined, undefined, undefined, { api: fake.api, owner: 'local', account: '31001001', mode: 'fixture' }, wordstat, ai);
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { await new Promise<void>(r => server.close(() => r())); db.close(); rmSync(dir, { recursive: true }); });
  const addr = server.address(); assert.ok(addr && typeof addr !== 'string'); const origin = `http://127.0.0.1:${addr.port}`;
  const post = (path: string, values: URLSearchParams, site = origin) => fetch(origin + path, { method:'POST',headers:{Origin:site},body:values,redirect:'manual' });
  const act = (action: string, values: Record<string,string> = {}) => post('/preparation/' + action, new URLSearchParams({ policyHash, preparationRevision: String(db.readPreparation('local')?.revision ?? 0), ...values }));
  assert.equal((await post('/preparation/entry', new URLSearchParams(), 'https://other.test')).status,403);
  for (const action of ['suggest','strategy','strategy-confirm','research']) assert.equal((await post('/direct/'+action,new URLSearchParams({aiConsent:'yes',paid:'yes'}))).status,409);
  assert.equal(profiles+requests+judgments,0);
  assert.equal((await act('entry',{...sample.draft,goal:'Обращения по доставке'})).status,303);
  assert.equal((await act('profile')).status,400); assert.equal(profiles,0);
  const request = new URLSearchParams({preparationRevision:String(db.readPreparation('local')!.revision),aiConsent:'yes'});
  assert.equal((await post('/preparation/profile',request)).status,303);
  assert.equal((await post('/preparation/profile',request)).status,409); assert.equal(profiles,1);
  const fields: Record<string,string> = {profileEditor:'yes',ownBrands:sample.profile.ownBrands.join('\n'),uncertainty:sample.profile.uncertainty.join('\n')};
  sample.profile.offers.forEach((o,i)=>Object.assign(fields,{['offer'+i]:i===0?'Суши с доставкой':o.name,['offerId'+i]:o.id,['kind'+i]:o.kind,['evidence'+i]:o.evidence,['aliases'+i]:o.aliases.join('\n'),['seeds'+i]:o.seeds.join('\n'),...(o.delivery?{['delivery'+i]:'yes'}:{})}));
  sample.profile.exclusions.forEach((x,i)=>Object.assign(fields,{['exclude'+i]:x.phrase,['excludeEvidence'+i]:x.evidence}));
  assert.equal((await act('confirm-profile',fields)).status,303);
  assert.equal((await act('research',{researchConsent:'yes',judgeConsent:'yes'})).status,303);
  assert.deepEqual([profiles,requests,judgments],[1,4,1]);
  assert.equal((await act('research',{researchConsent:'yes',judgeConsent:'yes'})).status,303); assert.deepEqual([profiles,requests,judgments],[1,4,1]);
  const run=db.readRuns('local').find(r=>r.kind==='research')!;
  const choose=new URLSearchParams({policyHash,preparationRevision:String(db.readPreparation('local')!.revision),phrases:'',manualReview:'yes'});
  for(const c of run.plan.candidates.filter(c=>c.selected)) choose.append('selected',c.phrase);
  assert.equal((await post('/preparation/offer',choose)).status,303);
  assert.equal((await act('confirm',{confirmPlan:'yes'})).status,303);
  const saved=db.readPreparation('local')!, plan=db.readPlan('local',saved.value.confirmedPlanId)!;
  const prepare=new URLSearchParams({campaignPlanId:plan.id,revision:String(plan.campaignRevision),name:'Один план',weekly:'300'});
  assert.equal((await post('/direct/prepare',prepare)).status,303);
  const state=db.readDirect('local')!;
  assert.equal((await post('/direct/create',new URLSearchParams({planId:state.planId,confirm:'yes'}))).status,303);
  assert.equal(db.readDirect('local')!.complete,true); assert.deepEqual(fake.records.adgroups[0].NegativeKeywords.Items,['пиццу']);
  assert.equal(fake.records.keywords.length,plan.phrases.length+1);
  const exported=await fetch(origin+'/preparation/research.json'); assert.equal(exported.status,200); assert.doesNotMatch(await exported.text(),/Authorization|never-log/);
  const overview = await (await fetch(origin)).text();
  assert.match(overview, /chip-draft[\s\S]*Черновик/);
  assert.match(overview, /Учебное подключение/);
  assert.doesNotMatch(overview, /<dt>Расход по Директу<\/dt>/);
  const html = await (await fetch(origin + '/campaign?ad=default')).text();
  assert.match(html, /<h2>Сводка<\/h2>/);
  assert.match(html, /Показы выключены/);
  const ids=[...html.matchAll(/\sid="([^"]+)"/g)].map(m=>m[1]);assert.equal(new Set(ids).size,ids.length);
});

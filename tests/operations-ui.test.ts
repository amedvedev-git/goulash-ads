test('аналитика: общая стоимость, ноль, отсутствие и неполнота не смешиваются', () => {
  const state = makeDemo('control');
  const render = () => renderDemoSection({ demo: { state, revision: 1, datasetId: 'test' }, history: [] });
  const totals = (html: string) => html.match(/<dl class="metrics"[\s\S]*?<\/dl>/)![0];
  const html = render();
  assert.match(totals(html), /Достижения цели<\/dt><dd>6/);
  assert.ok(totals(html).includes(money(50000)), 'aggregate cost includes both campaigns');
  assert.ok(html.includes(money(20000)), 'campaign B cost remains 200');
  assert.match(html, /0 · подтверждённый ноль/);
  assert.ok(html.indexOf('id="demo-statistics"') < html.indexOf('id="datasets"'));
  state.campaigns[0].goals = null;
  assert.match(totals(render()), /Нет полных данных/);
  assert.doesNotMatch(totals(render()), /<dd>6<\/dd>/);
  assert.match(totals(render()), /Не вычисляется/);
  state.campaigns.forEach((c) => { c.goals = 0; });
  assert.match(totals(render()), /Достижения цели<\/dt><dd>0/);
  assert.match(totals(render()), /Не вычисляется/);
  state.complete = false;
  assert.match(render(), /полученная часть отчёта/);
  assert.doesNotMatch(render(), /подтверждённый ноль/);
  assert.doesNotMatch(render(), /NaN|Infinity/);
  state.complete = true; state.updatedAt = new Date(Date.now() - 25 * 3600000).toISOString();
  assert.match(render(), /Устаревшие данные/);
  assert.match(renderDemoSection({ demo: { state, revision: 1, datasetId: 'test' }, history: [] }), /Правило не изменит бюджет/);
  state.goal = '<script>bad</script>';
  assert.doesNotMatch(render(), /<script>bad/); assert.match(render(), /&lt;script&gt;/);
});

test('HTTP: просмотр отмены без записи, явное подтверждение, гонка и повтор', async (t) => {
  const directory = mkdtempSync(join(tmpdir(), 'goulash-operations-ui-'));
  const db = openDatabase(directory), server = createApp(db);
  t.after(async () => { await new Promise<void>((resolve) => server.close(() => resolve())); db.close(); rmSync(join(directory, 'stage2.sqlite')); rmdirSync(directory); });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const address = server.address(); assert.ok(address && typeof address !== 'string');
  const origin = `http://127.0.0.1:${address.port}`;
  const get = (path: string) => fetch(origin + path, { signal: t.signal });
  const post = (path: string, data: Record<string, string>) => fetch(origin + path, {
    method: 'POST', headers: { Origin: origin }, body: new URLSearchParams(data), redirect: 'manual', signal: t.signal,
  });
  const empty = await (await get('/automation')).text();
  assert.match(empty, /Открыть готовый пример/);
  assert.doesNotMatch(empty, /id="control-plan"/);
  assert.equal((await post('/demo/load', { revision: '0', preset: demoPreset, planId: 'foreign', scenario: 'control' })).status, 409);
  assert.equal((await post('/demo/load', { revision: '0', preset: demoPreset, scenario: 'control' })).status, 303);
  const initial = db.readDemo('local')!;
  assert.equal(initial.state.planRef, undefined);
  assert.equal((await post('/demo/permission', { enabled: 'yes', confirm: 'control', revision: '0', datasetId: initial.datasetId })).status, 303);
  for (let attempt = 0; attempt < 100 && !db.operationsView('local').result; attempt++)
    await new Promise(resolve => setTimeout(resolve, 30));
  assert.equal(db.readPlans('local').length, 0);
  assert.equal(db.readCampaign('local'), undefined);
  assert.equal(db.readDirectRuns('local').length, 0);
  assert.equal(db.readDemo('local')!.state.campaigns[1].remaining - initial.state.campaigns[1].remaining, 70000);
  const entry = db.operationsView('local').result!;
  const resultPage = await (await get('/automation')).text();
  assert.match(resultPage, /перенесены из А в Б/);
  assert.match(resultPage, /Почему остановили[\s\S]*Куда ушёл остаток[\s\S]*Общий бюджет/);
  assert.match(resultPage, /Отменить решение/);
  const count = db.readHistory('local').length;
  const preview = await (await get(`/history?review=${entry.id}`)).text();
  assert.match(preview, /Проверьте отмену/); assert.match(preview, /После отмены/);
  assert.ok(preview.includes(money(300000))); assert.match(preview, /Подтвердить отмену/);
  assert.equal(db.readHistory('local').length, count, 'GET must not mutate');
  assert.equal((await post('/operations/undo', { id: entry.id })).status, 400);
  assert.equal(db.readHistory('local').length, count);
  const filter = '?scope=demo&by=goulash';
  const filteredJournal = await (await get('/history' + filter)).text();
  assert.ok(filteredJournal.includes(`/history?scope=demo&amp;by=goulash&amp;review=${entry.id}#undo-review`));
  const scopedReview = await (await get('/history' + filter + '&review=' + entry.id)).text();
  assert.ok(scopedReview.includes('action="/operations/undo?scope=demo&amp;by=goulash"'));
  const confirmed = await post('/operations/undo' + filter, { id: entry.id, confirm: 'undo' });
  assert.match(confirmed.headers.get('location')!, /scope=demo&by=goulash&undo=ok&operation=/);
  assert.equal(confirmed.status, 303);
  assert.doesNotMatch(confirmed.headers.get('location')!, /#/, 'success notice must not be scrolled away by a fragment');
  assert.deepEqual(db.readDemo('local')!.state, initial.state);
  const undoId = db.readOperation('local', entry.id)!.undoneBy!;
  const linked = await (await get(`/history?operation=${undoId}`)).text();
  assert.match(linked, new RegExp(`operation=${entry.id}`));
  assert.match(await (await get('/automation')).text(), /Решение отменено/);
  assert.equal((await post('/operations/undo', { id: entry.id, confirm: 'undo' })).status, 303);
  assert.equal(db.readHistory('local').length, count + 1, 'repeat does not create another undo');
  const repeated = await post('/demo/run', { datasetId: initial.datasetId });
  assert.equal(repeated.headers.get('location'), '/results?demo=repeat#demo');
  assert.deepEqual(db.readDemo('local')!.state, initial.state);
  const draft = { ...exampleCampaign, title: 'Первый', adText: 'Описание объявления' };
  db.saveCampaign('local', draft, 0); db.saveCampaign('local', { ...draft, title: 'Второй' }, 1);
  const change = db.readHistory('local')[0];
  assert.match(await (await get(`/history?review=${change.id}`)).text(), /Подтвердить отмену/);
  db.saveCampaign('local', { ...draft, title: 'Третий' }, 2);
  const conflict = await post('/operations/undo', { id: change.id, confirm: 'undo' });
  assert.equal(conflict.status, 409); const conflictHtml = await conflict.text();
  assert.match(conflictHtml, /Актуальное состояние сохранено/);
  assert.doesNotMatch(conflictHtml, /Подтвердить отмену/);
  assert.equal(db.readCampaign('local')!.draft.title, 'Третий');
  const filtered = await (await get('/history?scope=draft')).text();
  assert.match(filtered, /Правка черновика/); assert.doesNotMatch(filtered, /id="operation-.*Загрузка тестового набора/s);
  const badOrigin = await fetch(origin + '/operations/undo', { method: 'POST', headers: { Origin: 'https://invalid.example' }, body: new URLSearchParams({ id: change.id, confirm: 'undo' }) });
  assert.equal(badOrigin.status, 403);
});

test('связи истории и результат доступны за пределами 100 записей, только владельцу', async (t) => {
  const directory = mkdtempSync(join(tmpdir(), 'goulash-history-links-'));
  const db = openDatabase(directory), server = createApp(db);
  t.after(async () => { await new Promise<void>((resolve) => server.close(() => resolve())); db.close(); rmSync(join(directory, 'stage2.sqlite')); rmdirSync(directory); });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const address = server.address(); assert.ok(address && typeof address !== 'string');
  const origin = `http://127.0.0.1:${address.port}`;
  loadControl(db, 'local', 'control', 0, 'Тест'); const data = db.readDemo('local')!;
  db.enqueueDemo('local', data.datasetId, 'Тест'); db.processDemoJob();
  const old = db.operationsView('local').result!;
  for (let revision = 0; revision < 105; revision++) db.saveCampaign('local', { ...exampleCampaign, title: `Заголовок ${revision}`, adText: 'Текст' }, revision);
  assert.equal(db.readHistory('local').length, 100);
  assert.equal(db.operationsView('local').result?.id, old.id);
  const focus = await (await fetch(`${origin}/history?operation=${old.id}`)).text();
  assert.match(focus, /Выбранная операция[\s\S]*Кампания А остановлена[\s\S]*Куда ушёл остаток/);
  assert.equal(db.reviewUndo('local', old.id).status, 'ready');
  assert.equal(db.readOperation('other', old.id), undefined); assert.equal(db.reviewUndo('other', old.id).status, 'missing');
  db.saveCampaign('other', { ...exampleCampaign, title: 'Чужая секретная строка', adText: 'Текст' }, 0);
  const foreign = db.readHistory('other')[0];
  for (const query of ['review', 'operation']) {
    const response = await fetch(`${origin}/history?${query}=${foreign.id}`);
    assert.equal(response.status, 404); assert.doesNotMatch(await response.text(), /Чужая секретная строка/);
  }
});

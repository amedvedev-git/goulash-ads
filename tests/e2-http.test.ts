import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync,rmSync } from 'node:fs';
import { join,dirname,resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { once } from 'node:events';
import { e2Browser } from './fixtures/e2-browser.ts';
test('E2 HTTP: штатные формы подключения/CSRF/подтверждение/создание/отключение/история и другой owner',async t=>{
  const directory=mkdtempSync(join(tmpdir(),'e2-http-')),x=e2Browser(directory);x.server.listen(0,'127.0.0.1');await once(x.server,'listening');
  t.after(async()=>{await new Promise<void>(r=>x.server.close(()=>r()));x.db.close();assert.equal(dirname(resolve(directory)),resolve(tmpdir()));rmSync(directory,{recursive:true,force:true});});
  const origin=`http://127.0.0.1:${(x.server.address() as any).port}`;
  const login=await fetch(origin+'/fixture-login/a',{redirect:'manual'});let cookie=login.headers.get('set-cookie')!.split(';')[0];
  const get=(path:string)=>fetch(origin+path,{headers:{Cookie:cookie},redirect:'manual'});
  const post=(path:string,fields:Record<string,string>={},source=origin)=>fetch(origin+path,{method:'POST',headers:{Cookie:cookie,Origin:source},body:new URLSearchParams(fields),redirect:'manual'});
  assert.equal((await post('/connections/direct/start',{},'https://elsewhere.invalid')).status,403);
  const start=await post('/connections/direct/start');assert.equal(start.status,303);cookie+='; '+start.headers.get('set-cookie')!.split(';')[0];
  let html=await (await get('/connections/direct')).text();
  assert.doesNotMatch(html,/oauth\.yandex\.ru\/authorize|fixture-direct-app|code_verifier|e2-fixture-a/);
  assert.match(html,/Учебный код/);
  assert.match(html,/name="code"[^>]*value="a"/);
  const hidden=(name:string)=>html.match(new RegExp(`name="${name}" value="([^"]*)"`))![1];
  const invalid=await post('/connections/direct/finish',{attemptId:hidden('attemptId'),nonce:hidden('nonce'),code:'bad-fixture-code'});assert.equal(invalid.status,409);const errorHtml=await invalid.text();assert.match(errorHtml,/aria-label="Разделы"/);assert.match(errorHtml,/id="notification"/);assert.doesNotMatch(errorHtml,/bad-fixture-code/);
  const retry=await post('/connections/direct/start');cookie=cookie.split('; ')[0]+'; '+retry.headers.get('set-cookie')!.split(';')[0];html=await (await get('/connections/direct')).text();
  const finish=await post('/connections/direct/finish',{attemptId:hidden('attemptId'),nonce:hidden('nonce'),code:'a'});assert.equal(finish.status,303);
  html=await (await get('/connections/direct')).text();assert.match(html,/Подтвердите свой кабинет/);
  assert.equal((await post('/connections/direct/activate',{candidateId:hidden('candidateId'),confirm:'yes'})).status,303);
  const account = x.db.readDirectConnection(x.owner)!;
  const data = { account: account.account, generation: String(account.generation),
    revision: String(x.db.readAnalyticsSettings(x.owner).revision), name: 'Учебное кафе', confirm: 'yes' };
  assert.doesNotMatch(await (await get('/connections/direct')).text(), /id="advertiser-name"/);
  const lookup = () => post('/connections/advertiser', { account: data.account, generation: data.generation, revision: data.revision, operation: 'lookup' });
  x.a.advertiser(null);
  const missing = await lookup();
  assert.equal(missing.status, 200);
  assert.match(await missing.text(), /Директ не передал сведения для автоматической сверки.[\s\S]*id="advertiser-name"/);
  assert.equal(x.db.readAnalyticsSettings(x.owner).advertisers, undefined);
  x.a.advertiser('Учебный рекламодатель');
  x.a.wrongAccount(true);
  assert.equal((await lookup()).status, 409);
  x.a.wrongAccount(false);
  const found = await lookup();
  assert.equal(found.status, 200);
  const foundHtml = await found.text();
  assert.match(foundHtml, /По данным Директа[\s\S]*Учебный рекламодатель[\s\S]*Подтвердить рекламодателя/);
  assert.doesNotMatch(foundHtml, /1234567890|id="advertiser-name"|Я сверил сведения/);
  assert.equal(x.db.readAnalyticsSettings(x.owner).advertisers, undefined);
  const automatic = { ...data, name: 'Учебный рекламодатель', source: 'direct' };
  x.a.advertiser('Учебное кафе');
  const changed = await post('/connections/advertiser', automatic);
  assert.equal(changed.status, 409);
  assert.match(await changed.text(), /Данные рекламодателя изменились[\s\S]*Учебное кафе/);
  assert.equal(x.db.readAnalyticsSettings(x.owner).advertisers, undefined);
  const invalidAdvertiser = await post('/connections/advertiser', { ...data, name: '' });
  assert.equal(invalidAdvertiser.status, 409); assert.match(await invalidAdvertiser.text(), /id="advertiser-name" aria-invalid="true"/);
  assert.equal((await post('/connections/advertiser', { ...automatic, name: 'Учебное кафе' })).status, 303);
  let settingsHtml = await (await get('/connections/direct')).text();
  assert.match(settingsHtml, /Учебное кафе<\/strong><\/dd><\/div><\/dl>[\s\S]*Проверено владельцем <time [^>]+>[^<]+МСК/);
  assert.doesNotMatch(settingsHtml, /Для подключения войдите в Яндексе как главный представитель/);
  assert.match(settingsHtml, /connection-badge ok">Учебный/);
  const revoke = { account: data.account, generation: data.generation, confirm: 'disconnect',
    disconnectProof: settingsHtml.match(/name="disconnectProof" value="([^"]+)"/)![1] };
  const firstSession = cookie;
  cookie = (await fetch(origin+'/fixture-login/a',{redirect:'manual'})).headers.get('set-cookie')!.split(';')[0];
  assert.equal((await post('/connections/direct/disconnect', revoke)).status, 409);
  await x.connect('yandex:202', 'b', 'fixture-session-b');
  cookie = (await fetch(origin+'/fixture-login/b',{redirect:'manual'})).headers.get('set-cookie')!.split(';')[0];
  assert.equal(String(x.db.readDirectConnection('yandex:202')!.generation), data.generation);
  assert.equal((await post('/connections/direct/disconnect', revoke)).status, 409);
  assert.ok(x.manager.resolve('yandex:202'));
  cookie = firstSession;
  const context = x.db.createCampaignWorkspace(x.owner).id;
  for (const path of ['/connections/direct/start', '/connections/direct/start?from=results', '/connections/direct/start?ad=invalid'])
    assert.equal((await post(path, {contextCampaign: context})).status, 404);
  assert.equal(x.db.readConnectAttempt(x.owner), undefined);
  cookie = '';
  const expired = await post('/connections/direct/disconnect?ad=' + context + '&from=results', {...revoke,contextCampaign: context});
  assert.equal(expired.status, 401);
  const destination = '/auth/yandex?return=' + encodeURIComponent('/connections/direct?ad=' + context + '&from=results');
  assert.ok((await expired.text()).includes(`href="${destination}"`));
  assert.ok(x.manager.resolve(x.owner));
  cookie = firstSession;
  await x.action('prepare',{name:'HTTP набор'});let state=x.db.readDirect(x.owner)!;
  assert.equal((await post('/direct/create',{planId:state.planId,storageRevision:String(state.storageRevision),confirm:'yes'})).status,303);
  const card = await get('/campaigns?ad=default');
  assert.equal(card.headers.get('location'), '/prepare?ad=default');
  html = await (await get('/prepare?ad=default')).text();
  assert.match(html, /9000123400000000123/);
  assert.match(html, /Бюджет стратегии/);
  assert.match(await (await get('/campaigns?ad=default&edit=1')).text(), /Сумма передаётся как бюджет стратегии Директа/);
  assert.equal((await post('/connections/direct/disconnect')).status,409);
  assert.equal((await post('/connections/direct/disconnect',revoke)).status,303);
  assert.doesNotMatch(await (await get('/connections/direct')).text(), /action="\/connections\/direct\/disconnect"/);
  assert.equal((await post('/connections/direct/disconnect',revoke)).status,409);
  const disconnected = await (await get('/')).text();
  assert.match(disconnected, /доступ к Директу отключён/i);
  assert.match(disconnected, /href="\/connections\/direct\?ad=default">Восстановить доступ к Директу/);
  html=await (await get('/history')).text();assert.match(html,/9000123400000000123/);assert.doesNotMatch(html,/Отменить изменение в Директе/);
  assert.equal((await post('/direct/create',{planId:state.planId,confirm:'yes'})).status,403);
  const reconnect = await post('/connections/direct/start');
  cookie=cookie.split('; ')[0]+'; '+reconnect.headers.get('set-cookie')!.split(';')[0];
  html=await (await get('/connections/direct')).text();
  assert.equal((await post('/connections/direct/finish',{ attemptId:hidden('attemptId'), nonce:hidden('nonce'), code:'a' })).status,303);
  html=await (await get('/connections/direct')).text();
  assert.equal((await post('/connections/direct/activate',{candidateId:hidden('candidateId'),confirm:'yes'})).status,303);
  settingsHtml=await (await get('/connections/direct')).text();
  assert.match(settingsHtml, /К сверке/); assert.doesNotMatch(settingsHtml, /Учебное кафе/);
  assert.equal((await post('/connections/advertiser', { ...data, revision:String(x.db.readAnalyticsSettings(x.owner).revision) })).status,409);
  assert.equal((await post('/connections/direct/disconnect', revoke)).status,409);
  cookie=(await fetch(origin+'/fixture-login/b',{redirect:'manual'})).headers.get('set-cookie')!.split(';')[0];
  html=await (await get('/history')).text();assert.doesNotMatch(html,/9000123400000000123|HTTP набор/);assert.equal(x.b.writes().length,0);
});
